# Rasterizes Inter (SIL OFL 1.1) glyphs and the Aegis artwork into anti-aliased tables for the display-node sketch.
# Needs Pillow. Usage: python3 tools/gen_assets.py <Inter[opsz,wght].ttf> assets.h
import math, sys
from PIL import Image, ImageDraw, ImageFont

if len(sys.argv) != 3:
    sys.exit('usage: gen_assets.py <Inter.ttf (variable)> <output assets.h>')
FONT, OUT = sys.argv[1], sys.argv[2]
CHARS = [chr(c) for c in range(32, 127)] + ['é', 'è', 'à', '’', '·']

# name, px size, weight
FONTS = [('R10', 10, 400), ('R11', 11, 400), ('R12', 12, 400), ('R13', 13, 400),
         ('S13', 13, 600), ('B14', 14, 700), ('B17', 17, 700), ('B20', 20, 700), ('B28', 28, 700)]

def load(size, wght):
    f = ImageFont.truetype(FONT, size)
    f.set_variation_by_axes([max(14, min(32, size)), wght])
    return f

lines = ['// Generated by gen_assets.py from Inter (SIL OFL 1.1). Do not edit.', '#pragma once', '#include "types.h"', '#include <pgmspace.h>', '']
for name, size, wght in FONTS:
    f = load(size, wght)
    ss = 4  # supersample for smoother coverage
    big = load(size * ss, wght)
    data = bytearray(); glyphs = []
    for ch in CHARS:
        adv = f.getlength(ch)
        bbox = big.getbbox(ch, anchor='ls')
        if bbox is None or bbox[2] <= bbox[0]:
            glyphs.append((ord(ch), len(data), 0, 0, 0, 0, int(round(adv * 256)))); continue
        l, t, r, b = bbox
        x0, y0 = math.floor(l / ss) - 1, math.floor(t / ss) - 1
        x1, y1 = math.ceil(r / ss) + 1, math.ceil(b / ss) + 1
        w, h = x1 - x0, y1 - y0
        img = Image.new('L', (w * ss, h * ss), 0)
        ImageDraw.Draw(img).text((-x0 * ss, -y0 * ss), ch, font=big, fill=255, anchor='ls')
        img = img.resize((w, h), Image.BOX)
        glyphs.append((ord(ch), len(data), w, h, x0, y0, int(round(adv * 256))))
        data += bytes(img.tobytes())
    lines.append('static const uint8_t %s_bits[] PROGMEM = {%s};' % (name, ','.join(str(v) for v in data)))
    lines.append('static const AAGlyph %s_glyphs[] PROGMEM = {%s};' % (name, ','.join('{%d,%d,%d,%d,%d,%d,%d}' % g for g in glyphs)))
    lines.append('static const AAFont FONT_%s = {%s_glyphs, %s_bits, %d};' % (name, name, name, len(glyphs)))
    lines.append('')

def rgb565(r, g, b): return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
def hexc(h): return tuple(int(h[i:i+2], 16) for i in (1, 3, 5))
def emit(name, img):
    px = img.convert('RGB'); w, h = px.size
    vals = [rgb565(*px.getpixel((x, y))) for y in range(h) for x in range(w)]
    lines.append('static const uint16_t %s[] PROGMEM = {%s};' % (name, ','.join('0x%04X' % v for v in vals)))
    lines.append('static const int %s_W = %d, %s_H = %d;' % (name, w, name, h))
    lines.append('')

SS = 8
BLUE, TEAL = hexc('#234BCE'), hexc('#087A9B')
def mark(size):
    s = size * SS
    img = Image.new('RGB', (s, s), (255, 255, 255)); d = ImageDraw.Draw(img); k = s / 64
    P = lambda pts: [(x * k, y * k) for x, y in pts]
    d.polygon(P([(4, 60), (27, 8), (38, 8), (15, 60)]), fill=BLUE)
    d.polygon(P([(38, 8), (61, 60), (49, 60), (32, 21)]), fill=BLUE)
    d.polygon(P([(32, 33), (40, 41), (32, 49), (24, 41)]), fill=TEAL)
    return img.resize((size, size), Image.LANCZOS)
emit('IMG_MARK108', mark(108))
emit('IMG_MARK22', mark(22))

def icon(bg, draw):
    s = 104 * SS
    img = Image.new('RGB', (s, s), (255, 255, 255)); d = ImageDraw.Draw(img)
    d.ellipse([0, 0, s - 1, s - 1], fill=hexc(bg))
    u = 52 / 24 * SS; ox = oy = 26 * SS  # 24-unit icon box, 52 px, centred
    P = lambda x, y: (ox + x * u, oy + y * u)
    draw(d, P, u)
    return img.resize((104, 104), Image.LANCZOS)
def stroke(d, pts, u, col, closed=False):
    w = int(2.2 * u)
    seq = pts + ([pts[0]] if closed else [])
    d.line(seq, fill=col, width=w, joint='curve')
    for p in seq: d.ellipse([p[0] - w / 2, p[1] - w / 2, p[0] + w / 2, p[1] + w / 2], fill=col)
def ic_ok(d, P, u): stroke(d, [P(4, 12.5), P(9.5, 18), P(20, 6.5)], u, TEAL)
def ic_exp(d, P, u):
    g = hexc('#5B6785'); c = P(12, 12); r = 8.5 * u; w = 2.2 * u
    d.ellipse([c[0] - r - w / 2, c[1] - r - w / 2, c[0] + r + w / 2, c[1] + r + w / 2], fill=g)
    d.ellipse([c[0] - r + w / 2, c[1] - r + w / 2, c[0] + r - w / 2, c[1] + r - w / 2], fill=hexc('#EEF1F7'))
    stroke(d, [P(12, 7), P(12, 12.5), P(15.5, 14.5)], u, g)
def ic_fail(d, P, u):
    r = hexc('#B3261E'); stroke(d, [P(6, 6), P(18, 18)], u, r); stroke(d, [P(18, 6), P(6, 18)], u, r)
def ic_anom(d, P, u):
    a = hexc('#A15C00'); stroke(d, [P(12, 4), P(21.5, 20), P(2.5, 20)], u, a, closed=True)
    stroke(d, [P(12, 10), P(12, 14.5)], u, a)
    c = P(12, 17.2); w = 2.2 * u
    d.ellipse([c[0] - w / 2, c[1] - w / 2, c[0] + w / 2, c[1] + w / 2], fill=a)
emit('IMG_ICON_OK', icon('#E3F4F8', ic_ok)); emit('IMG_ICON_EXPIRED', icon('#EEF1F7', ic_exp))
emit('IMG_ICON_FAILED', icon('#FDECEC', ic_fail)); emit('IMG_ICON_ANOMALY', icon('#FFF3DC', ic_anom))

# QR card: white rounded card with a 1 px border, anti-aliased corners.
cw, ch, rad = 216, 204, 10
s = SS
img = Image.new('RGB', (cw * s, ch * s), (255, 255, 255)); d = ImageDraw.Draw(img)
d.rounded_rectangle([0, 0, cw * s - 1, ch * s - 1], radius=rad * s, fill=hexc('#D7DFE9'))
d.rounded_rectangle([s, s, cw * s - 1 - s, ch * s - 1 - s], radius=(rad - 1) * s, fill=(255, 255, 255))
emit('IMG_CARD', img.resize((cw, ch), Image.LANCZOS))

open(OUT, 'w').write('\n'.join(lines) + '\n')
print('ok', len('\n'.join(lines)) // 1024, 'KB source')
